"""
DOCUMENTATION WRITER AGENT
-----------------------------
Purpose: write a concise incident narrative displayed in the Full Report section.

The report is stored in workflow state and persisted by main.py. Downloadable
PDF, Markdown, and text reports are generated by report_export.py from stored data.
"""

from state import IncidentState
from utils.report_export import build_live_report


def report_writer_agent(state: IncidentState) -> IncidentState:
    # The diagnostic agents already produced the facts and uncertainty fields.
    # Rendering them locally removes one serial Groq call and prevents report
    # prose from introducing claims that are absent from the evidence.
    print("\n[DOCUMENTATION WRITER AGENT] Rendering the structured incident report...")
    state["final_report"] = build_live_report(state)

    print("[DOCUMENTATION WRITER AGENT] Report ready for database storage")

    return {k: v for k, v in state.items() if k != "investigation_findings"}
